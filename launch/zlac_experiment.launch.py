"""Experiment bringup: per-run control parameters and passive ROS 2 CSV logging.

No motion command is generated by this launch file. Use the existing
navigation/teleoperation controller to supply /cmd_vel after safety checks.
Requires the zlac8015d_hardware devel/pid branch for pid_torque mode.
"""

import math
import os
import xml.etree.ElementTree as ET

import yaml
from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, OpaqueFunction, SetEnvironmentVariable
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


# Values are overridden in-memory in the installed URDF. The original file is
# never modified by an experiment run.
ARG_DEFAULTS = {
    "mode": "ladrc_torque",
    "pid_kp": "0.7",
    "pid_ki": "0.5",
    "pid_kd": "0.03",
    "pid_derivative_filter_tau_s": "0.05",
    "ladrc_b0_left": "18.0",
    "ladrc_b0_right": "18.0",
    "ladrc_wc": "5.0",
    "ladrc_wo": "20.0",
    "current_limit_a": "8.0",
    "current_rate_limit_a_per_s": "20.0",
    "feedback_timeout_ms": "30.0",
    "test_label": "speed_tracking",
    "planned_linear_m_s": "0.2",
    "planned_angular_rad_s": "0.0",
    "planned_duration_s": "10.0",
    "trial": "01",
    "surface": "unspecified",
    "disturbance": "none",
    "notes": "",
    "output_root": "~/ros2_experiments",
}

CONTROL_MODES = ("velocity", "ladrc_torque", "pid_torque")
GAIN_KEYS = (
    "pid_kp", "pid_ki", "pid_kd", "pid_derivative_filter_tau_s",
    "ladrc_b0_left", "ladrc_b0_right", "ladrc_wc", "ladrc_wo",
    "current_limit_a", "current_rate_limit_a_per_s", "feedback_timeout_ms",
)


def _expand_launch(context, *args, **kwargs):
    del args, kwargs
    values = {
        key: LaunchConfiguration(key).perform(context)
        for key in ARG_DEFAULTS
    }
    mode = values["mode"].strip()
    if mode not in CONTROL_MODES:
        raise ValueError(
            "mode must be velocity, ladrc_torque or pid_torque; got " + repr(mode)
        )

    numeric = {}
    for key in GAIN_KEYS + (
        "planned_linear_m_s", "planned_angular_rad_s", "planned_duration_s"
    ):
        try:
            value = float(values[key])
        except ValueError as exc:
            raise ValueError("{} must be a number".format(key)) from exc
        if not math.isfinite(value):
            raise ValueError("{} must be finite".format(key))
        numeric[key] = value

    if numeric["planned_duration_s"] <= 0:
        raise ValueError("planned_duration_s must be positive")
    for key in ("pid_kp", "pid_ki", "pid_kd"):
        if numeric[key] < 0:
            raise ValueError("{} must not be negative".format(key))
    if mode == "pid_torque" and (
        numeric["pid_kp"] + numeric["pid_ki"] + numeric["pid_kd"] <= 0
    ):
        raise ValueError("At least one PID gain must be positive.")
    for key in GAIN_KEYS:
        if key not in ("pid_kp", "pid_ki", "pid_kd") and numeric[key] <= 0:
            raise ValueError("{} must be positive".format(key))
    # The hardware sends signed mA as int16. Never request >30A.
    if numeric["current_limit_a"] > 30.0:
        raise ValueError("current_limit_a must not exceed 30.0 A")

    share = get_package_share_directory("zlac_can_bringup")
    urdf_path = os.path.join(share, "urdf", "orange_go_2025.urdf")
    controller_path = os.path.join(share, "config", "controllers.yaml")

    # The controller's wheel geometry is the authoritative value, rather
    # than repeating constants in the recorder or launch code.
    with open(controller_path, encoding="utf-8") as stream:
        controller_config = yaml.safe_load(stream)
    diff = controller_config["diff_drive_controller"]["ros__parameters"]
    wheel_radius = float(diff["wheel_radius"])
    wheel_separation = float(diff["wheel_separation"])
    cmd_timeout_s = float(diff.get("cmd_vel_timeout", 0.5))
    if min(wheel_radius, wheel_separation, cmd_timeout_s) <= 0:
        raise ValueError("Invalid diff_drive_controller wheel geometry/timeout.")

    tree = ET.parse(urdf_path)
    hardware = tree.find(".//ros2_control/hardware")
    if hardware is None:
        raise ValueError("The robot URDF has no ros2_control hardware element.")
    updates = {"control_mode": mode}
    updates.update({key: str(numeric[key]) for key in GAIN_KEYS})
    for name, value in updates.items():
        params = hardware.findall("./param[@name='{}']".format(name))
        if len(params) > 1:
            raise ValueError("Duplicate hardware param: " + name)
        param = params[0] if params else ET.SubElement(hardware, "param", name=name)
        param.text = value
    description = ET.tostring(tree.getroot(), encoding="unicode")

    recorder_parameters = {
        "mode": mode,
        "wheel_radius_m": wheel_radius,
        "wheel_separation_m": wheel_separation,
        "cmd_timeout_s": cmd_timeout_s,
        "test_label": values["test_label"],
        "trial": values["trial"],
        "surface": values["surface"],
        "disturbance": values["disturbance"],
        "notes": values["notes"],
        "output_root": values["output_root"],
    }
    recorder_parameters.update(numeric)

    # Force the hardware's optional environment override to agree with the
    # experiment launch argument. Do not leave a stale shell override active.
    return [
        SetEnvironmentVariable("ZLAC_CONTROL_MODE", mode),
        Node(
            package="robot_state_publisher",
            executable="robot_state_publisher",
            parameters=[{"robot_description": description}],
            output="screen",
        ),
        Node(
            package="controller_manager",
            executable="ros2_control_node",
            parameters=[{"robot_description": description}, controller_path],
            remappings=[
                ("/diff_drive_controller/cmd_vel_unstamped", "/cmd_vel"),
                ("/diff_drive_controller/odom", "/odom"),
            ],
            output="both",
        ),
        Node(
            package="zlac_can_bringup",
            executable="record_experiment.py",
            name="zlac_experiment_recorder",
            parameters=[recorder_parameters],
            output="screen",
        ),
        Node(
            package="controller_manager",
            executable="spawner",
            arguments=["joint_state_broadcaster", "--controller-manager", "/controller_manager"],
        ),
        Node(
            package="controller_manager",
            executable="spawner",
            arguments=["diff_drive_controller", "--controller-manager", "/controller_manager"],
        ),
    ]


def generate_launch_description():
    return LaunchDescription([
        *[
            DeclareLaunchArgument(key, default_value=default)
            for key, default in ARG_DEFAULTS.items()
        ],
        OpaqueFunction(function=_expand_launch),
    ])
